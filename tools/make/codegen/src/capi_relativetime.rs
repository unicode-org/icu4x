use std::{fs::File, io::Write, path::PathBuf};

use askama::Template;

pub const GENERATED_BY: &str = std::concat!("@generated by ", std::file!());

struct Unit {
    singular: &'static str,
    plural: &'static str,
}

const WIDTHS: &[&str] = &["long", "short", "narrow"];

const UNITS: &[Unit] = &[
    Unit {
        singular: "second",
        plural: "seconds",
    },
    Unit {
        singular: "minute",
        plural: "minutes",
    },
    Unit {
        singular: "hour",
        plural: "hours",
    },
    Unit {
        singular: "day",
        plural: "days",
    },
    Unit {
        singular: "week",
        plural: "weeks",
    },
    Unit {
        singular: "month",
        plural: "months",
    },
    Unit {
        singular: "quarter",
        plural: "quarters",
    },
    Unit {
        singular: "year",
        plural: "years",
    },
];

#[derive(Template)]
#[template(path = "relativetime.rs.jinja", escape = "none")]
struct RelativeTimeTemplate {
    widths: &'static [&'static str],
    units: &'static [Unit],
}

pub fn main() {
    let mut path_buf = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    path_buf.push("../../../ffi/capi/src/relativetime.rs");
    let mut file = File::create(&path_buf).unwrap();
    let template = RelativeTimeTemplate {
        widths: WIDTHS,
        units: UNITS,
    };
    writeln!(&mut file, "{template}").unwrap();
}
