static FILE_HEADER: &str = r##"# This file contains all APIs that are exposed in Rust but not over FFI, and not allowlisted in IGNORED_PATHS in tools/ffi_coverage/allowlist.rs.
# It is generated by `cargo make diplomat-coverage`.
#
# If adding an API that expands this file, please consider:
#
#  - Whether you can expose that API over FFI in the same PR (and if you do so, be sure to add a `rust_link` annotation)
#  - Whether the API already has its functionality exposed over FFI (if so, add a potentially-`hidden` `rust_link` annotation to the corresponding FFI API)
#  - Whether that API is rust-specific functionality that need not be exposed (if so, add it to the allowlist with a note, or add a `hidden` `rust_link` annotation to a related API if possible)
#  - Whether that API should be punted for later in FFI (if so, please check in with @Manishearth, @robertbastian, or @sffc)
#  - Whether the API is unstable (if so, add it to the allowlist as unstable)
#
# It is acceptable to temporarily have APIs in this file that you plan to add in a soon-upcoming PR.
#
# Please check in with @Manishearth, @robertbastian, or @sffc if you have questions

"##;
/// RustLink but without display information
#[derive(PartialEq, Eq, Debug, Clone, PartialOrd, Ord, Hash)]
struct RustLinkInfo {
    path: ast::Path,
    typ: ast::DocType,
}

impl fmt::Display for RustLinkInfo {
    fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
        write!(f, "{}#{:?}", self.path, self.typ)
    }
}

fn main() {
    run_util_api_enforcement();

    let out_path = std::env::args().nth(1);
    let doc_types = ["icu", "fixed_decimal", "icu_provider_adapters"]
        .into_iter()
        .flat_map(collect_public_types)
        .map(|(path_vec, typ)| {
            let mut path = ast::Path::empty();
            path.elements = path_vec.into_iter().map(ast::Ident::from).collect();
            RustLinkInfo { path, typ }
        })
        .filter(|rl| {
            ![
                ast::DocType::EnumVariant,
                ast::DocType::Mod,
                ast::DocType::Trait,
            ]
            .contains(&rl.typ)
        })
        .collect::<BTreeSet<_>>();

    let capi_crate = PathBuf::from(concat!(
        std::env!("CARGO_MANIFEST_DIR"),
        "/../../../ffi/capi/src/lib.rs"
    ));
    eprintln!("Loading icu_capi crate from {capi_crate:?}");
    let capi_types = ast::File::from(&syn_inline_mod::parse_and_inline_modules(&capi_crate))
        .all_rust_links()
        .into_iter()
        .cloned()
        .map(|rl| RustLinkInfo {
            path: rl.path,
            typ: rl.typ,
        })
        .collect::<BTreeSet<_>>();

    let mut file_anchor = None;
    let mut stdout_anchor = None;
    let out_stream = if let Some(out_path) = out_path {
        let stream = file_anchor.insert(File::create(out_path).expect("opening output file"));
        stream as &mut dyn std::io::Write
    } else {
        let stream = stdout_anchor.insert(std::io::stdout());
        stream as &mut dyn std::io::Write
    };
    writeln!(out_stream, "{FILE_HEADER}").unwrap();
    doc_types
        .difference(&capi_types)
        .for_each(|item| writeln!(out_stream, "{item}").unwrap());
}

fn parse_doc(krate: &str) -> &'static Crate {
    lazy_static::lazy_static! {
        static ref CRATES: elsa::sync::FrozenMap<String, Box<Crate>> = elsa::sync::FrozenMap::new();
    }

    if CRATES.get(krate).is_none() {
        eprintln!("Parsing crate {krate}");
        std::process::Command::new("rustup")
            .args(["install", "nightly-2025-09-27"])
            .output()
            .expect("failed to install nightly");
        let output = std::process::Command::new("rustup")
            .args([
                "run",
                "nightly-2025-09-27",
                "cargo",
                "rustdoc",
                "-p",
                krate,
                "--all-features",
                "--",
                "-Zunstable-options",
                "--output-format",
                "json",
            ])
            .env_remove("RUSTDOCFLAGS")
            .output()
            .expect("failed to execute rustdoc");
        if !output.status.success() {
            panic!("Rustdoc build failed with {output:?}");
        }
        let path = PathBuf::from(std::env!("CARGO_MANIFEST_DIR"))
            .join("../../../target/doc")
            .join(krate)
            .with_extension("json");
        eprintln!("Attempting to load {path:?}");
        CRATES.insert(
            krate.to_owned(),
            serde_json::from_slice(&fs::read(&path).unwrap()).unwrap(),
        );
    }
    CRATES.get(krate).unwrap()
}

fn collect_public_types(krate: &str) -> impl Iterator<Item = (Vec<String>, ast::DocType)> {
    #[derive(Debug)]
    enum In<'a> {
        Trait,
        // The Option<String> is for the trait name of an impl
        Enum(Option<&'a str>),
        Struct(Option<&'a str>),
        Type(Option<&'a str>),
    }

    fn recurse(
        item: &Item,
        krate: &Crate,
        types: &mut HashSet<(Vec<String>, ast::DocType)>,
        mut path: Vec<String>,
        path_already_extended: bool,
        inside: Option<In>,
    ) {
        fn ignored(path: &Vec<String>) -> bool {
            IGNORED_PATHS.contains(path)
                || path
                    .last()
                    .map(|l| IGNORED_SUBSTRINGS.iter().any(|i| l.contains(i)))
                    .unwrap_or(false)
        }
        /// Helper function that ensures that ignored()
        /// is respected for every type inserted
        ///
        /// (We have a check at the beginning of recurse() but that won't catch leaf nodes)
        fn insert_ty(
            types: &mut HashSet<(Vec<String>, ast::DocType)>,
            path: Vec<String>,
            ty: ast::DocType,
        ) {
            if !ignored(&path) {
                types.insert((path, ty));
            }
        }

        fn check_ignored_assoc_item(name: &str, trait_path: Option<&str>) -> bool {
            if let Some(tr) = trait_path
                && let Some(ignored) = IGNORED_ASSOCIATED_ITEMS.get(tr)
                && ignored.contains(&name)
            {
                return true;
            }
            false
        }

        if ignored(&path) || item.deprecation.is_some() {
            return;
        }
        match &item.inner {
            ItemEnum::Use(import) => {
                if !import.is_glob {
                    path.push(import.name.clone());
                }

                if let Some(item) = &krate.index.get(import.id.as_ref().unwrap()) {
                    recurse(item, krate, types, path, true, None);
                } else if let Some(item) = &krate.paths.get(import.id.as_ref().unwrap()) {
                    // This is a reexport of hidden items, which work fine in HTML doc but
                    // don't seem to be reachable anywhere in JSON.
                    if let Some(item) = import
                        .source
                        .as_str()
                        .strip_prefix("icu_provider::fallback::")
                    {
                        insert_ty(
                            types,
                            vec![
                                "icu".to_string(),
                                "locale".to_string(),
                                "fallback".to_string(),
                                item.to_string(),
                            ],
                            match item {
                                "LocaleFallbackPriority" | "LocaleFallbackSupplement" => {
                                    ast::DocType::Enum
                                }
                                "LocaleFallbackConfig" => ast::DocType::Struct,
                                e => unreachable!("{e:?}"),
                            },
                        );
                        return;
                    }

                    // External crate. This is quite complicated and while it works, I'm not sure
                    // it's correct. This basically handles the case `pub use other_crate::module::Struct`,
                    // which means we have to parse `other_crate`, then look for `module`, then look
                    // for `Struct`. Now, `module` could actually be a reexport, which is why we have to
                    // check the `Import` case when traversing the path.
                    let external_crate = parse_doc(&krate.external_crates[&item.crate_id].name);
                    let mut item = &external_crate.index[&external_crate.root];
                    for segment in import.source.split("::").skip(1) {
                        match &item.inner {
                            ItemEnum::Module(inner) => {
                                item = inner
                                    .items
                                    .iter()
                                    .map(|id| &external_crate.index[id])
                                    .find(|item| match &item.inner {
                                        ItemEnum::Use(import) => {
                                            if import.name.as_str() == segment {
                                                path.pop();
                                                true
                                            } else {
                                                false
                                            }
                                        }
                                        _ => item.name.as_deref() == Some(segment),
                                    })
                                    .expect(&import.source);
                            }
                            _ => unreachable!(),
                        }
                    }
                    recurse(item, external_crate, types, path, true, None);
                } else {
                    eprintln!("{path:?} should be in either index or paths");
                }
            }
            _ => {
                let item_name = item.name.as_ref().unwrap();
                if !path_already_extended {
                    path.push(item_name.clone());
                }
                match &item.inner {
                    ItemEnum::Module(module) => {
                        for id in &module.items {
                            recurse(&krate.index[id], krate, types, path.clone(), false, None);
                        }
                        insert_ty(types, path, ast::DocType::Mod);
                    }
                    ItemEnum::Struct(structt) => {
                        for id in &structt.impls {
                            if let ItemEnum::Impl(inner) = &krate.index[id].inner {
                                let mut trait_name = None;
                                if let Some(path) = &inner.trait_ {
                                    if IGNORED_TRAITS.contains(path.path.as_str()) {
                                        continue;
                                    }
                                    trait_name = Some(path.path.as_str());
                                }
                                for id in &inner.items {
                                    recurse(
                                        &krate.index[id],
                                        krate,
                                        types,
                                        path.clone(),
                                        false,
                                        Some(In::Struct(trait_name)),
                                    );
                                }
                            }
                        }

                        insert_ty(types, path, ast::DocType::Struct);
                    }
                    ItemEnum::Enum(enumm) => {
                        for id in &enumm.variants {
                            recurse(&krate.index[id], krate, types, path.clone(), false, None);
                        }

                        for id in &enumm.impls {
                            if let ItemEnum::Impl(inner) = &krate.index[id].inner {
                                let mut trait_name = None;
                                if let Some(path) = &inner.trait_ {
                                    if IGNORED_TRAITS.contains(path.path.as_str()) {
                                        continue;
                                    }
                                    trait_name = Some(path.path.as_str());
                                }
                                for id in &inner.items {
                                    recurse(
                                        &krate.index[id],
                                        krate,
                                        types,
                                        path.clone(),
                                        false,
                                        Some(In::Enum(trait_name)),
                                    );
                                }
                            }
                        }

                        insert_ty(types, path, ast::DocType::Enum);
                    }
                    ItemEnum::Trait(inner) => {
                        for id in &inner.items {
                            recurse(
                                &krate.index[id],
                                krate,
                                types,
                                path.clone(),
                                false,
                                Some(In::Trait),
                            );
                        }
                        insert_ty(types, path, ast::DocType::Trait);
                    }
                    ItemEnum::Constant { .. } => {
                        insert_ty(types, path, ast::DocType::Constant);
                    }
                    ItemEnum::Function(_) => {
                        let doc_type = match inside {
                            Some(In::Enum(tr)) | Some(In::Struct(tr)) | Some(In::Type(tr))
                                if check_ignored_assoc_item(item_name, tr) =>
                            {
                                return;
                            }
                            Some(In::Enum(_)) => ast::DocType::FnInEnum,
                            Some(In::Trait) => ast::DocType::FnInTrait,
                            Some(In::Struct(_)) => ast::DocType::FnInStruct,
                            Some(In::Type(_)) => ast::DocType::FnInTypedef,
                            _ => ast::DocType::Fn,
                        };
                        insert_ty(types, path, doc_type);
                    }
                    ItemEnum::Macro(_) => {
                        insert_ty(types, path, ast::DocType::Macro);
                    }
                    ItemEnum::TypeAlias(t) => {
                        if let Type::ResolvedPath(p) = &t.type_
                            && let ItemEnum::Struct(rustdoc_types::Struct { impls, .. })
                            | ItemEnum::Enum(rustdoc_types::Enum { impls, .. }) =
                                &krate.index[&p.id].inner
                        {
                            for id in impls {
                                if let ItemEnum::Impl(inner) = &krate.index[id].inner {
                                    let mut trait_name = None;
                                    if let Some(path) = &inner.trait_ {
                                        if IGNORED_TRAITS.contains(path.path.as_str()) {
                                            continue;
                                        }
                                        trait_name = Some(path.path.as_str());
                                    }
                                    for id in &inner.items {
                                        recurse(
                                            &krate.index[id],
                                            krate,
                                            types,
                                            path.clone(),
                                            false,
                                            Some(In::Type(trait_name)),
                                        );
                                    }
                                }
                            }
                        }
                        insert_ty(types, path, ast::DocType::Typedef);
                    }
                    ItemEnum::Variant(_) => {
                        insert_ty(types, path, ast::DocType::EnumVariant);
                    }
                    ItemEnum::AssocConst { .. } => {
                        // Skip
                    }
                    ItemEnum::AssocType { .. } => {
                        // Skip
                    }
                    ItemEnum::ProcMacro(..) => {}
                    _ => todo!("{:?}", item),
                }
            }
        }
    }

    let mut types = HashSet::new();
    let krate = parse_doc(krate);

    recurse(
        &krate.index[&krate.root],
        krate,
        &mut types,
        Vec::new(),
        false,
        None,
    );

    types.into_iter()
}

fn run_util_api_enforcement() {
    let (component_crates, util_crates) = discover_workspace_crates();

    // Bucket 1: Definitely Stable util crates
    let bucket1_utils: HashSet<&str> = [
        "writeable",
        "fixed_decimal",
        "tinystr",
        "yoke",
        "yoke-derive",
        "zerofrom",
        "zerofrom-derive",
        "zerovec",
        "zerovec-derive",
    ]
    .into_iter()
    .collect();

    // Bucket 2: Ambiguous / Low-Risk util crates (restricted to explicit allowlist)
    let bucket2_allowlist: HashSet<(&str, &str)> = [
        ("icu_calendar", "calendrical_calculations"),
        ("icu_calendar", "ixdtf"),
        ("icu_time", "ixdtf"),
        ("icu_locale_core", "litemap"),
        ("icu_locale_core", "potential_utf"),
        ("icu_collections", "potential_utf"),
        ("icu_casemap", "potential_utf"),
        ("icu_locale", "potential_utf"),
    ]
    .into_iter()
    .collect();

    let bucket2_utils: HashSet<&str> = bucket2_allowlist.iter().map(|(_, u)| *u).collect();

    // Bucket 3: Default for all remaining util crates (Internal only)
    let bucket3_utils: HashSet<&str> = util_crates
        .iter()
        .map(|s| s.as_str())
        .filter(|u| !bucket1_utils.contains(u) && !bucket2_utils.contains(u))
        .collect();

    // Assert that every discovered util crate belongs to one of the 3 buckets
    for u in &util_crates {
        assert!(
            bucket1_utils.contains(u.as_str())
                || bucket2_utils.contains(u.as_str())
                || bucket3_utils.contains(u.as_str()),
            "Util crate '{u}' is not categorized in any bucket!"
        );
    }

    let mut all_violations = Vec::new();
    for krate_name in &component_crates {
        let krate = parse_doc(krate_name);
        let violations = check_crate_util_api_enforcement(
            krate_name,
            krate,
            &bucket2_allowlist,
            &bucket2_utils,
            &bucket3_utils,
        );
        all_violations.extend(violations);
    }

    if !all_violations.is_empty() {
        eprintln!("\nUtil crate public API enforcement violations found:");
        for v in &all_violations {
            eprintln!("  [ERROR] {v}");
        }
        std::process::exit(1);
    }
}

#[derive(Deserialize)]
struct CargoMetadata {
    packages: Vec<CargoPackage>,
}

#[derive(Deserialize)]
struct CargoPackage {
    name: String,
    manifest_path: String,
}

fn discover_workspace_crates() -> (Vec<String>, HashSet<String>) {
    let output = std::process::Command::new("cargo")
        .args(["metadata", "--format-version", "1", "--no-deps"])
        .output()
        .expect("failed to execute cargo metadata");

    if !output.status.success() {
        panic!("cargo metadata failed: {:?}", output);
    }

    let metadata: CargoMetadata =
        serde_json::from_slice(&output.stdout).expect("failed to parse cargo metadata output");

    let mut component_crates = Vec::new();
    let mut util_crates = HashSet::new();

    for pkg in metadata.packages {
        let path = pkg.manifest_path.replace('\\', "/");
        if (path.contains("/components/") || path.contains("/provider/core/"))
            && !pkg.name.ends_with("-dev")
            && !pkg.name.contains("codepointtrie")
            && !pkg.name.contains("experimental")
        {
            component_crates.push(pkg.name);
        } else if path.contains("/utils/") {
            util_crates.insert(pkg.name);
        }
    }

    component_crates.sort();
    (component_crates, util_crates)
}

fn is_util_module_match(source: &str, util_name: &str) -> bool {
    let source_bytes = source.as_bytes();
    let util_bytes = util_name.as_bytes();

    if source_bytes.len() < util_bytes.len() {
        return false;
    }

    for (sb, ub) in source_bytes.iter().zip(util_bytes.iter()) {
        let expected = if *ub == b'-' { b'_' } else { *ub };
        if *sb != expected {
            return false;
        }
    }

    if source_bytes.len() == util_bytes.len() {
        return true;
    }

    source_bytes[util_bytes.len()..].starts_with(b"::")
}

fn check_crate_util_api_enforcement(
    krate_name: &str,
    krate: &Crate,
    bucket2_allowlist: &HashSet<(&str, &str)>,
    bucket2_utils: &HashSet<&str>,
    bucket3_utils: &HashSet<&str>,
) -> Vec<String> {
    let mut violations = Vec::new();
    let mut visited = HashSet::new();

    fn walk_item(
        id: &rustdoc_types::Id,
        krate_name: &str,
        krate: &Crate,
        visited: &mut HashSet<rustdoc_types::Id>,
        violations: &mut Vec<String>,
        bucket2_allowlist: &HashSet<(&str, &str)>,
        bucket2_utils: &HashSet<&str>,
        bucket3_utils: &HashSet<&str>,
        is_provider: bool,
    ) {
        if !visited.insert(id.clone()) {
            return;
        }

        if let Some(item) = krate.index.get(id) {
            if item.visibility != rustdoc_types::Visibility::Public {
                return;
            }

            let is_provider_item = is_provider
                || item.name.as_deref() == Some("provider")
                || item.name.as_deref() == Some("baked");

            match &item.inner {
                ItemEnum::Module(module) => {
                    for child_id in &module.items {
                        walk_item(
                            child_id,
                            krate_name,
                            krate,
                            visited,
                            violations,
                            bucket2_allowlist,
                            bucket2_utils,
                            bucket3_utils,
                            is_provider_item,
                        );
                    }
                }
                ItemEnum::Use(import) => {
                    if !is_provider_item {
                        for util in bucket3_utils {
                            if is_util_module_match(&import.source, util) {
                                violations.push(format!(
                                    "Bucket 3 violation in {krate_name}: pub use {}",
                                    import.source
                                ));
                            }
                        }
                    }
                    for util in bucket2_utils {
                        if is_util_module_match(&import.source, util) {
                            if !bucket2_allowlist.contains(&(krate_name, util)) {
                                violations.push(format!(
                                    "Bucket 2 violation in {krate_name}: pub use {} (not allowlisted)",
                                    import.source
                                ));
                            }
                        }
                    }
                    if let Some(ref target_id) = import.id {
                        walk_item(
                            target_id,
                            krate_name,
                            krate,
                            visited,
                            violations,
                            bucket2_allowlist,
                            bucket2_utils,
                            bucket3_utils,
                            is_provider_item,
                        );
                    }
                }
                ItemEnum::Function(func) => {
                    let mut referenced = HashSet::new();
                    for (_name, ty) in &func.sig.inputs {
                        get_type_crates(ty, krate, &mut referenced);
                    }
                    if let Some(ref output) = func.sig.output {
                        get_type_crates(output, krate, &mut referenced);
                    }
                    for util in referenced {
                        if bucket3_utils.contains(util) && !is_provider_item {
                            violations.push(format!(
                                "Bucket 3 violation in {krate_name}::fn {}: uses internal util '{util}'",
                                item.name.as_deref().unwrap_or("<unnamed>")
                            ));
                        } else if bucket2_utils.contains(util)
                            && !bucket2_allowlist.contains(&(krate_name, util))
                        {
                            violations.push(format!(
                                "Bucket 2 violation in {krate_name}::fn {}: uses low-risk util '{util}' outside allowlist",
                                item.name.as_deref().unwrap_or("<unnamed>")
                            ));
                        }
                    }
                }
                ItemEnum::Struct(struct_) => {
                    let field_ids: Vec<Option<&rustdoc_types::Id>> = match &struct_.kind {
                        rustdoc_types::StructKind::Plain { fields, .. } => {
                            fields.iter().map(Some).collect()
                        }
                        rustdoc_types::StructKind::Tuple(fields) => {
                            fields.iter().map(|f| f.as_ref()).collect()
                        }
                        _ => Vec::new(),
                    };
                    for fid in field_ids {
                        if let Some(field_id) = fid {
                            if let Some(field_item) = krate.index.get(field_id) {
                                if field_item.visibility == rustdoc_types::Visibility::Public {
                                    if let ItemEnum::StructField(ref fty) = field_item.inner {
                                        let mut referenced = HashSet::new();
                                        get_type_crates(fty, krate, &mut referenced);
                                        for util in referenced {
                                            if bucket3_utils.contains(util) && !is_provider_item {
                                                violations.push(format!(
                                                    "Bucket 3 violation in {krate_name}::{}.{}: uses internal util '{util}'",
                                                    item.name.as_deref().unwrap_or("<unnamed>"),
                                                    field_item.name.as_deref().unwrap_or("<unnamed>")
                                                ));
                                            } else if bucket2_utils.contains(util)
                                                && !bucket2_allowlist.contains(&(krate_name, util))
                                            {
                                                violations.push(format!(
                                                    "Bucket 2 violation in {krate_name}::{}.{}: uses low-risk util '{util}' outside allowlist",
                                                    item.name.as_deref().unwrap_or("<unnamed>"),
                                                    field_item.name.as_deref().unwrap_or("<unnamed>")
                                                ));
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
                _ => {}
            }
        }
    }

    walk_item(
        &krate.root,
        krate_name,
        krate,
        &mut visited,
        &mut violations,
        bucket2_allowlist,
        bucket2_utils,
        bucket3_utils,
        false,
    );

    violations
}

fn get_type_crates<'a>(ty: &Type, krate: &'a Crate, crates: &mut HashSet<&'a str>) {
    match ty {
        Type::ResolvedPath(path) => {
            if let Some(item) = krate.paths.get(&path.id) {
                if item.crate_id != 0 {
                    if let Some(ext) = krate.external_crates.get(&item.crate_id) {
                        crates.insert(ext.name.as_str());
                    }
                }
            }
            if let Some(ref args) = path.args {
                if let rustdoc_types::GenericArgs::AngleBracketed { ref args, .. } = **args {
                    for arg in args {
                        if let rustdoc_types::GenericArg::Type(inner_ty) = arg {
                            get_type_crates(inner_ty, krate, crates);
                        }
                    }
                }
            }
        }
        Type::BorrowedRef { type_, .. } => {
            get_type_crates(type_, krate, crates);
        }
        Type::Slice(type_) => {
            get_type_crates(type_, krate, crates);
        }
        Type::Tuple(types) => {
            for t in types {
                get_type_crates(t, krate, crates);
            }
        }
        _ => {}
    }
}
